#!/usr/bin/env python3
"""Write the teaser URLs into the style metadata, demo notes and gallery."""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STYLES = ROOT / "skills" / "filmcode" / "library" / "styles"
DEMO = ROOT / "demo"
TEASERS = json.loads((DEMO / "teaser" / "styles.json").read_text(encoding="utf-8"))
BASE = "https://veqhxcsoalfnbsbycnwb.supabase.co/storage/v1/object/public/filmcode-demos"
REAL = {"crayon-book", "ascii-crt"}   # hand-built demos, not generated style cards
WATER_URL = f"{BASE}/watercolor.mp4"
ORDER = ["Edit & Documentary", "Evidence Films", "Hand-drawn & Painting", "East Asian Traditions",
         "Print & Printmaking", "Graphic & Type", "Information & Keynote", "Cartoon & Anime",
         "Games", "Cinema & Eras", "Materials & 3D"]


def meta(slug):
    return json.loads((STYLES / slug / "style.json").read_text(encoding="utf-8"))


def hex6(h):
    h = h.lstrip("#")
    return "#" + ("".join(c * 2 for c in h) if len(h) == 3 else h)


def main():
    styles = {p.parent.name: json.loads(p.read_text(encoding="utf-8")) for p in STYLES.glob("*/style.json")}

    # style.json: public demo URL, new-title metadata
    for e in TEASERS:
        if e["slug"] in REAL:
            continue
        p = STYLES / e["slug"] / "style.json"
        d = json.loads(p.read_text(encoding="utf-8"))
        d["film"] = e["topic"]
        d["line"] = f'A 10-second {d["en"]} style teaser: "{e["topic"]}".'
        d["dur"] = 10.0
        d["frame_sec"] = 5.0
        d["demo"] = f"{BASE}/{e['slug']}.mp4"
        d["demo_topic"] = e["topic"]
        d["demo_seconds"] = 10
        p.write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        styles[e["slug"]] = d
    wp = STYLES / "watercolor" / "style.json"
    wd = json.loads(wp.read_text(encoding="utf-8"))
    wd["demo"] = WATER_URL
    wd["demo_topic"] = "Alborada"
    wd["demo_seconds"] = 45
    wp.write_text(json.dumps(wd, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    styles["watercolor"] = wd

    # style index with a watch link for every row
    idx = ["# Style index", "",
           "Users may name a style in English or by its folder. Find it here, then read `styles/<folder>/STYLE.md`.",
           "<!-- generated by styleboard/build.py from styles/*/style.json; do not edit by hand -->", ""]
    for cat in ORDER:
        group = sorted([s for s in styles.values() if s["category_en"] == cat], key=lambda s: int(s["num"]))
        if not group:
            continue
        idx += [f"## {cat}", "", "| Style | Folder | Our demo |", "|---|---|---|"]
        for s in group:
            url = WATER_URL if s["slug"] == "watercolor" else f"{BASE}/{s['slug']}.mp4"
            label = f"*{s.get('demo_topic') or s['film']}*"
            if s.get("demo_seconds"):
                label += f" ({s['demo_seconds']} s)"
            idx.append(f"| {s['en']} | [`{s['slug']}`]({s['slug']}/STYLE.md) | {label} · [notes](../../../../demo/{s['slug']}/DEMO.md) · [watch]({url}) |")
        idx.append("")
    (STYLES / "README.md").write_text("\n".join(idx).rstrip() + "\n", encoding="utf-8")

    # short teaser notes; the old reference-demo breakdowns are not kept
    for e in TEASERS:
        if e["slug"] in REAL:
            continue
        p = DEMO / e["slug"] / "DEMO.md"
        c = e["colors"]
        doc = (
            f"# {e['en']} — 10 s teaser\n\n"
            f"Watch: [10 s teaser]({BASE}/{e['slug']}.mp4) — \"{e['topic']}\"\n\n"
            f"A 10-second style card for FilmCode ({e['category']}): palette `{c['bg']}`, `{c['accent']}`, "
            f"`{c['support']}`, `{c['ink']}`; a {e['type']} typeface; a {e['motif']} motion motif. "
            "Silent, generated, not a story.\n\n"
            f"Style rules: [STYLE.md](../../skills/filmcode/library/styles/{e['slug']}/STYLE.md)\n"
        )
        p.write_text(doc, encoding="utf-8")

    # Watercolor keeps its real 45 s film and source, but not the old reference breakdown.
    wd = json.loads((STYLES / "watercolor" / "style.json").read_text(encoding="utf-8"))
    (DEMO / "watercolor" / "DEMO.md").write_text(
        "# Watercolor Brush — Alborada\n\n"
        f"Watch: [45 s demo]({WATER_URL}) · poster [poster.jpg](poster.jpg) · source [source/](source/)\n\n"
        f"45.0 s, 1920x1080, 30 fps, stereo sound. {wd['line']}\n\n"
        "Style rules: [STYLE.md](../../skills/filmcode/library/styles/watercolor/STYLE.md) · "
        "build notes: [source/SOURCE.md](source/SOURCE.md)\n",
        encoding="utf-8",
    )

    # gallery page
    cards = []
    for e in TEASERS:
        s = styles[e["slug"]]
        cards.append({
            "slug": e["slug"], "en": e["en"], "category": e["category"], "topic": e["topic"],
            "film": s["film"], "colors": e["colors"], "url": f"{BASE}/{e['slug']}.mp4", "seconds": 10,
            "num": int(s["num"]),
        })
    cards.append({"slug": "watercolor", "en": "Watercolor Brush", "category": "Hand-drawn & Painting",
                  "topic": "Alborada", "film": "Alborada",
                  "colors": {"bg": "#f4efe3", "ink": "#1d1a17", "accent": "#d2402f", "support": "#2e8b57"},
                  "url": WATER_URL, "seconds": 45, "num": int(styles["watercolor"]["num"])})
    cards.sort(key=lambda c: c["num"])

    card_html = []
    for c in cards:
        bg, ink = hex6(c["colors"]["bg"]), hex6(c["colors"]["ink"])
        sw = "".join(f'<i class="sw" style="background:{hex6(c["colors"][k])}"></i>' for k in ("bg", "accent", "support", "ink"))
        poster = f' poster="{c["slug"]}/poster.jpg"'
        card_html.append(
            f'<article class="card" style="background:{bg};color:{ink};border-color:{ink}2e">'
            f'<video controls playsinline preload="none"{poster} src="{c["url"]}"></video>'
            f'<p class="cat">{html.escape(c["category"])}</p>'
            f'<h2>{html.escape(c["en"])}</h2>'
            f'<p class="topic">&ldquo;{html.escape(c["topic"])}&rdquo;</p>'
            f'<div class="swatches">{sw}</div>'
            f'<a class="watch" style="border-color:{ink}3d" href="{c["url"]}" target="_blank" rel="noopener">'
            f'Open <span>{c["seconds"]} s</span></a></article>'
        )

    page = f"""<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>FilmCode demos</title>
<style>
  :root {{ color-scheme: dark; }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: #0d0f12; color: #ece8de; font: 16px/1.45 'Helvetica Neue', Helvetica, Arial, sans-serif; }}
  header, .wrap, footer {{ max-width: 1280px; margin: 0 auto; padding: 0 24px; }}
  header {{ padding-top: 52px; }}
  h1 {{ font-size: clamp(2.1rem, 5vw, 3.6rem); letter-spacing: -.03em; margin: 0 0 10px; }}
  .lede {{ color: #a5abb4; max-width: 62ch; margin: 0; }}
  .grid {{ display: grid; grid-template-columns: repeat(auto-fill, minmax(300px, 1fr)); gap: 16px; padding-top: 28px; padding-bottom: 60px; }}
  .card {{ border: 1px solid; border-radius: 14px; padding: 14px; display: flex; flex-direction: column; }}
  .card video {{ display: block; width: 100%; aspect-ratio: 16 / 9; border-radius: 9px; background: #000; margin-bottom: 12px; }}
  .cat {{ font-size: .68rem; letter-spacing: .14em; text-transform: uppercase; opacity: .7; margin: 0; }}
  h2 {{ font-size: 1.2rem; line-height: 1.12; margin: .42rem 0 .3rem; }}
  .topic {{ opacity: .82; margin: 0 0 auto; font-size: .96rem; }}
  .swatches {{ display: flex; gap: 6px; margin: 14px 0 12px; }}
  .sw {{ width: 18px; height: 18px; border-radius: 4px; border: 1px solid rgba(0,0,0,.18); }}
  .watch {{ display: flex; justify-content: space-between; border-top: 1px solid; padding-top: 10px; color: inherit; text-decoration: none; font-weight: 700; }}
  .watch span {{ opacity: .62; font-weight: 500; }}
  footer {{ padding-bottom: 52px; color: #7f858e; font-size: .86rem; }}
  a {{ color: #8ecbff; }}
</style>
<body>
<header>
  <h1>FilmCode demos</h1>
  <p class="lede">Every style has a demo. Watercolor is a 45-second film, Crayon Picture Book and ASCII / CRT Terminal are hand-built 10-second films, and the other styles are 10-second style teasers. Every video plays in the page.</p>
</header>
<main class="wrap"><div class="grid">
{chr(10).join(card_html)}
</div></main>
<footer>FilmCode · <a href="https://github.com/dv-hoang/filmcode">repository</a></footer>
</body>
</html>
"""
    (DEMO / "index.html").write_text(page, encoding="utf-8")

    # README demo section
    readme = ROOT / "README.md"
    t = readme.read_text(encoding="utf-8")
    section = ("## Demo video\n\n"
               "Every style has a demo: Watercolor is a 45 s film, Crayon Picture Book and ASCII / CRT Terminal are "
               "hand-built 10 s films, and the other 63 styles are 10 s style teasers. Every video plays in "
               "[`demo/index.html`](demo/index.html). Enable GitHub Pages (Settings -> Pages -> Deploy from a branch -> "
               "`main` / root) and open `https://dv-hoang.github.io/filmcode/demo/`.\n\n")
    t = re.sub(r"## Demo video\n.*?\n## Layout", section + "## Layout", t, flags=re.S)
    readme.write_text(t, encoding="utf-8")

    # AGENTS.md / SKILL.md: every style has a hosted demo
    demo_url = f"{BASE}/<slug>.mp4"
    agents = ROOT / "skills" / "filmcode" / "library" / "AGENTS.md"
    t = agents.read_text(encoding="utf-8")
    t = re.sub(r"^- The demo notes for every style.*$",
               f"- Every style has a demo hosted on Supabase: `{demo_url}` (10 s), and Watercolor's 45 s film is "
               f"`{WATER_URL}`. URLs are in `demo/<slug>/DEMO.md` and `demo/index.html`; the demo notes and videos are "
               "outside the installed skill.", t, flags=re.M)
    agents.write_text(t, encoding="utf-8")

    skill = ROOT / "skills" / "filmcode" / "SKILL.md"
    t = skill.read_text(encoding="utf-8")
    t = re.sub(r"^\| Demo films \|.*$",
               f"| Demo films | Every style has a demo hosted on Supabase: `{demo_url}` (10 s), and Watercolor's 45 s film is "
               f"`{WATER_URL}`. URLs are in `demo/<slug>/DEMO.md` and `demo/index.html`, outside the installed skill. "
               "Read a demo note only after `TREATMENT.md` is written; other sources are not included. |", t, flags=re.M)
    skill.write_text(t, encoding="utf-8")

    print(f"updated {len(cards)} gallery cards and {len(TEASERS)} teaser docs")


if __name__ == "__main__":
    main()
